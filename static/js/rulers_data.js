/**
 * Get planet symbol(s) as string for display
 * @param {string[]} planets - array of planet names
 * @returns {string} unicode symbols joined
 */
function getRulerSymbols(planets) {
  return planets.map(p => PLANET_SYM[p] || p).join('');
}

/**
 * Get nidana rulers for a given gate and line
 * @param {number} gate
 * @param {number} line
 * @returns {{ up: string, down: string } | null}
 */
function getNidanaRulers(gate, line) {
  const key = `${gate}.${line}`;
  const entry = RULERS_NIDANA[key];
  if (!entry) return null;
  return {
    up: getRulerSymbols(entry.up),
    down: getRulerSymbols(entry.down),
    upPlanets: entry.up || [],
    downPlanets: entry.down || [],
  };
}
